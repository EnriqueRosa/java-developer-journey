// Declara una variable de tipo String con tu localidad, y a continuación cambia su valor y vuelve a imprimirla.
public class Variables07 {
    public static void main(String[] args) {
        String myString = ("Palma De Mallorca");
        System.out.println(myString);

        myString = ("Barcelona"); //Cambia el valor
        System.out.println(myString); //Imprime el nuevo valor
    }
}

