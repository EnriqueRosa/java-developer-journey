//Tema 1: Variables y Constantes

public class Variables {
    public static void main(String[] args) {

        String name = "Enrique";  // La variables NAME és el que guarda o contiene el nombre "Enrique"
            System.out.println(name);

            int age = 21;  // La variable INT AGE és de tipo entero y almacena el valor de la edad.
                System.out.println(age);

        //Constantes

        final String EMAIL = "enrique@gmail.com";
        System.out.println(EMAIL);

        //La palabra FINAL és un candado. Es un dato que és fijo y no se puede cambiar en todo el programa.

    }
}
