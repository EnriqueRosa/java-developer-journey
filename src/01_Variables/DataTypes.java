//Tipos de datos primitivos

public class DataTypes {
    public static void main(String[] args) {

        int myInt = 21; // El dato INT hace servir los datos enteros
        System.out.println(myInt);

        double myDouble = 1.80; //El dato DOUBLE hace referencia a los decimales
        System.out.println(myDouble);

        char myChar = 'e'; //El dato CHAR hace servir el tipo de dato caracter
        System.out.println(myChar);

        boolean myBoolean = true; //El dato BOOLEAN hace referencia si es verdadero o falso
        System.out.println(myBoolean);
    }
}
